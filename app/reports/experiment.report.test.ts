import { writeFileSync } from "fs";
import { join } from "path";
import { thirtyDayWishlistToPurchaseRate } from "@/analytics/metrics";
import { simulate } from "@/analytics/simulate";
import { RAMP_STEPS, assign, tally } from "@/experiment/assignment";
import { ExperimentFlag } from "@/experiment/flags";
import { DEFAULT_THRESHOLDS, evaluateGuardrails } from "@/experiment/guardrails";
import { alwaysValidInterval, fixedHorizonInterval, peekingDemo } from "@/experiment/sequential";

const REPORT = join(__dirname, "..", "..", "docs", "experiment-report.md");
const POPULATION = Array.from({ length: 50_000 }, (_, i) => `u_${i}`);
const DAY = "2026-08-26";

/**
 * The E10 read-out (plan S10 and S12+), written to docs/experiment-report.md.
 *
 * Everything here is real: assignment, the ramp, the guardrails and the
 * sequential bound are measured on the actual implementation. Only the
 * *population* is synthetic, and only where a population is needed at all.
 */
describe("experiment report", () => {
  it("writes docs/experiment-report.md", () => {
    // Ramp balance, and the property that makes a staged ramp valid.
    const rampRows = RAMP_STEPS.filter((step) => step > 0).map((ramp) => {
      const counts = tally(POPULATION, { ramp });
      return {
        ramp,
        exposed: counts.exposed / counts.total,
        a: counts.treatment_a,
        b: counts.treatment_b,
      };
    });

    let moved = 0;
    let carried = 0;
    let previous = POPULATION.map((u) => assign(u, { ramp: RAMP_STEPS[1] }));
    for (const ramp of RAMP_STEPS.slice(2)) {
      const current = POPULATION.map((u) => assign(u, { ramp }));
      previous.forEach((before, i) => {
        if (!before.exposed) return;
        carried += 1;
        if (current[i].arm !== before.arm || !current[i].exposed) moved += 1;
      });
      previous = current;
    }

    // The kill-switch drill.
    const flag = new ExperimentFlag();
    flag.advance(DAY, "1%");
    flag.advance(DAY, "5%");
    flag.advance(DAY, "20%");
    const armsBefore = POPULATION.slice(0, 5000).map((u) => flag.arm(u));
    const exposedBefore = armsBefore.filter((a) => a !== "control").length;

    const { log } = simulate({ users: 4000, seed: 7, liftTreatmentA: -0.12, liftTreatmentB: -0.14 });
    const damaged = log.all();
    const readings = evaluateGuardrails(damaged, DEFAULT_THRESHOLDS);
    const tripped = flag.check(damaged, DAY);
    const exposedAfter = POPULATION.slice(0, 5000)
      .map((u) => flag.arm(u))
      .filter((a) => a !== "control").length;

    // Sequential vs fixed-horizon, on a healthy run.
    const healthy = simulate({ users: 6000, seed: 8 });
    const healthyEvents = healthy.log.all();
    const cohortOf = (armName: "control" | "treatment_a" | "treatment_b") =>
      thirtyDayWishlistToPurchaseRate(healthyEvents, healthy.asOf, armName);
    const control = cohortOf("control");
    const b = cohortOf("treatment_b");
    const obs = {
      control: { successes: control.converted, trials: control.entered },
      treatment: { successes: b.converted, trials: b.entered },
    };
    const fixed = fixedHorizonInterval(obs.control, obs.treatment);
    const sequential = alwaysValidInterval(obs.control, obs.treatment);

    const peeking = peekingDemo(300, 40, 100, 0.2, 99);
    const fixedRate = peeking.fixedHorizonFalsePositives / peeking.runs;
    const seqRate = peeking.sequentialFalsePositives / peeking.runs;

    const lines = [
      "# Experiment harness read-out (E10)",
      "",
      "Generated by `npm run experiment`. Regenerate rather than edit.",
      "",
      "Assignment, the ramp, the guardrails and the sequential bound are measured",
      "on the real implementation. Only the *population* is synthetic, and only",
      "where one is needed at all.",
      "",
      "## 1. Assignment and the staged ramp",
      "",
      `${POPULATION.length.toLocaleString("en-IN")} users, hashed with the default salt.`,
      "",
      "| Ramp | Exposed | Treatment A | Treatment B |",
      "|---|---|---|---|",
      ...rampRows.map(
        (row) =>
          `| ${(row.ramp * 100).toFixed(0)}% | ${(row.exposed * 100).toFixed(2)}% | ${row.a.toLocaleString("en-IN")} | ${row.b.toLocaleString("en-IN")} |`
      ),
      "",
      "### Monotonicity",
      "",
      `Across every ramp step, **${moved} of ${carried.toLocaleString("en-IN")}** already-exposed users changed arm or fell out of the experiment.`,
      "",
      "This is the property a staged ramp rests on and the one most easily lost.",
      "The obvious implementation — bucket into arms, then take the first N% of",
      "each — looks correct and silently reshuffles at every step, restarting the",
      "experiment without any visible symptom. Exposure and arm are hashed",
      "independently here, so raising the ramp can only ever add users.",
      "",
      "## 2. Kill-switch drill — the S10 gate",
      "",
      "| | |",
      "|---|---|",
      `| Ramp before | ${(RAMP_STEPS[3] * 100).toFixed(0)}% |`,
      `| Exposed users in a 5,000 sample | ${exposedBefore.toLocaleString("en-IN")} |`,
      `| Guardrail breach detected | ${tripped ? "yes" : "no"} |`,
      `| Reason | ${flag.killedReason ?? "—"} |`,
      `| Exposed users immediately after | ${exposedAfter} |`,
      "",
      "| Guardrail | Threshold | Reading | Breached |",
      "|---|---|---|---|",
      ...readings.map(
        (reading) =>
          `| ${reading.label} | ${reading.threshold} | ${reading.detail} | ${reading.breached ? "**yes**" : reading.undetermined ? "undetermined" : "no"} |`
      ),
      "",
      "The switch is **sticky**: it stays tripped once the numbers recover, and",
      "only a human can clear it. A treatment that recovers on its own would",
      "otherwise flap in and out of the population, which is worse for users and",
      "for the data than either state alone. Clearing it restores the arms users",
      "already had rather than reshuffling mid-experiment.",
      "",
      "A minimum sample of " + DEFAULT_THRESHOLDS.minimumSample + " observations applies to every guardrail. A switch",
      "that fires on nine sessions gets disabled by the first person it wakes.",
      "",
      "## 3. Sequential vs fixed-horizon inference",
      "",
      "A staged ramp means looking at the numbers repeatedly, and a fixed-horizon",
      "test is valid only if you look exactly once, at a sample size fixed in",
      "advance. Peeking is not a minor sin here — it is arithmetic.",
      "",
      "### Measured cost of peeking, on data with no effect at all",
      "",
      `Both arms drawn from the same distribution, ${peeking.runs} runs, ${peeking.peeks} peeks each. Every declaration below is a false positive by construction.`,
      "",
      "| Method | Declared significance | Nominal |",
      "|---|---|---|",
      `| Fixed-horizon, peeked ${peeking.peeks}× | **${(fixedRate * 100).toFixed(1)}%** | 5% |`,
      `| Confidence sequence | **${(seqRate * 100).toFixed(1)}%** | 5% |`,
      "",
      `Peeking inflates the fixed-horizon error rate to ${(fixedRate * 100).toFixed(1)}% — ${(fixedRate / 0.05).toFixed(1)}× its nominal level. The confidence sequence holds.`,
      "",
      "### Applied to a healthy simulated run",
      "",
      "| Method | Difference (B − control) | Interval | Significant |",
      "|---|---|---|---|",
      `| Fixed-horizon | ${(fixed.difference * 100).toFixed(2)}pp | ${(fixed.lower * 100).toFixed(2)} to ${(fixed.upper * 100).toFixed(2)}pp | ${fixed.significant ? "yes" : "no"} |`,
      `| Always-valid | ${(sequential.difference * 100).toFixed(2)}pp | ${(sequential.lower * 100).toFixed(2)} to ${(sequential.upper * 100).toFixed(2)}pp | ${sequential.significant ? "yes" : "no"} |`,
      "",
      "The always-valid interval is wider at every moment. That width is the price",
      "of being allowed to stop whenever you like, and it is cheaper than the",
      "alternative — which is not a narrower interval but an invalid one.",
      "",
      "## What this report is not evidence for",
      "",
      "- Assignment balance is measured on sequential synthetic ids. Real ids are less uniform, and the hash should be re-checked against a sample of them.",
      "- The guardrail readings come from a simulated population whose damage was injected deliberately. They demonstrate that the switch fires; they say nothing about whether the real treatment is harmful.",
      "- The sequential bound is a normal-mixture confidence sequence with a fixed tuning parameter. It is valid, not optimal — a different ρ trades early width against late width.",
      "- Nothing here establishes that Treatment B beats Treatment A. That is what the experiment is for, and it has not been run.",
      "",
    ];

    writeFileSync(REPORT, lines.join("\n"));

    expect(moved).toBe(0);
    expect(tripped).toBe(true);
    expect(exposedAfter).toBe(0);
    expect(fixedRate).toBeGreaterThan(seqRate);
  });
});
